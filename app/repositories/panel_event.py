from sqlalchemy import text

from uuid import uuid4

from app.database import engine

VALID_EVENTS = {
    "POSTER_ADDED",
    "VISIBLE",
    "COVERED",
    "PARTIALLY_COVERED",
    "EMPTY",
    "POSTER_REMOVED",
}


def add_panel_event(
    panel_id: str,
    event_type: str,
    comment: str | None = None,
    source: str = "user",
    source_id: str | None = None,
):
    """
    Add a new event to a panel's history.

    The event timestamp is automatically generated by PostgreSQL.
    """

    if event_type not in VALID_EVENTS:
        raise ValueError(
            f"Invalid event type: {event_type}. Expected one of {sorted(VALID_EVENTS)}"
        )

    event_id = str(uuid4())

    query = text("""
        INSERT INTO panel_events (
            event_id,
            panel_id,
            event_type,
            comment,
            source_id,
            source
        )
        VALUES (
            :event_id,
            :panel_id,
            :event_type,
            :comment,
            :source_id,
            :source
        )
        RETURNING created_at
    """)

    with engine.begin() as conn:
        created_at = conn.execute(
            query,
            {
                "event_id": event_id,
                "panel_id": panel_id,
                "event_type": event_type,
                "comment": comment,
                "source_id": source_id,
                "source": source,
            },
        ).scalar_one()

    return {
        "event_id": event_id,
        "panel_id": panel_id,
        "event_type": event_type,
        "created_at": created_at,
        "comment": comment,
        "source_id": source_id,
        "source": source,
    }


def get_panel_history(panel_id: str):
    """
    Return the complete history of a panel,
    ordered from oldest to newest event.
    """

    query = text("""
        SELECT
            event_id,
            panel_id,
            created_at,
            event_type,
            comment,
            source_id,
            source
        FROM panel_events
        WHERE panel_id = :panel_id
        ORDER BY created_at ASC
    """)

    with engine.connect() as conn:
        rows = (
            conn.execute(
                query,
                {
                    "panel_id": panel_id,
                },
            )
            .mappings()
            .all()
        )

    return [dict(row) for row in rows]


def get_latest_panel_event(panel_id: str):
    """
    Return the most recent event for a panel.
    """

    query = text("""
        SELECT
            event_id,
            panel_id,
            created_at,
            event_type,
            comment,
            source_id,
            source
        FROM panel_events
        WHERE panel_id = :panel_id
        ORDER BY created_at DESC
        LIMIT 1
    """)

    with engine.connect() as conn:
        row = (
            conn.execute(
                query,
                {"panel_id": panel_id},
            )
            .mappings()
            .first()
        )

    if row is None:
        return None

    return dict(row)
